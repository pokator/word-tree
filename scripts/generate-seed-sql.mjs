// Generates supabase/seed.sql from the live src/data/japaneseData.js module,
// so the Supabase seed data can never drift from (or be mistyped versus)
// the static fallback fixture. Run with: node scripts/generate-seed-sql.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { KANJI, WORDS } from "../src/data/japaneseData.js";

const sqlString = (s) => `'${s.replace(/'/g, "''")}'`;
const sqlArray = (arr) => (arr.length === 0 ? "ARRAY[]::text[]" : `ARRAY[${arr.map(sqlString).join(",")}]`);

const kanjiRows = Object.values(KANJI)
  .map((k) => `  (${sqlString(k.char)}, ${sqlString(k.meaning)}, ${sqlArray(k.onyomi)}, ${sqlArray(k.kunyomi)})`)
  .join(",\n");

const wordRows = WORDS.map(
  (w) => `  (${sqlString(w.word)}, ${sqlString(w.reading)}, ${sqlString(w.meaning)}, ${sqlArray(w.components)})`
).join(",\n");

const sql = `-- Generated by scripts/generate-seed-sql.mjs from src/data/japaneseData.js.
-- Do not hand-edit -- regenerate instead so this can never drift from the
-- static fallback fixture. Run once in the Supabase SQL editor, after
-- supabase/schema.sql.

insert into public.kanji (char, meaning, onyomi, kunyomi) values
${kanjiRows}
on conflict (char) do nothing;

insert into public.words (word, reading, meaning, components) values
${wordRows}
on conflict (word) do nothing;
`;

const outPath = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "supabase", "seed.sql");
writeFileSync(outPath, sql, "utf8");
console.log(`Wrote ${outPath} (${Object.keys(KANJI).length} kanji, ${WORDS.length} words)`);
