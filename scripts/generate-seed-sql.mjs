// Generates supabase/seed.sql from the bundled local dataset
// (public/data/{kanji,words}.json -- see public/data/README.md for
// provenance), so the Supabase seed data can never drift from (or be
// mistyped versus) what the app already ships offline. Run with:
//   node scripts/generate-seed-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { extractKanjiComponents } from "../src/graph/kanji.js";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const KANJI = JSON.parse(readFileSync(path.join(ROOT, "public/data/kanji.json"), "utf8"));
const WORDS = JSON.parse(readFileSync(path.join(ROOT, "public/data/words.json"), "utf8"));

const CHUNK_SIZE = 500;

const sqlString = (s) => `'${String(s ?? "").replace(/'/g, "''")}'`;
const sqlInt = (n) => (n === null || n === undefined ? "null" : String(n));
const sqlArray = (arr) => (!arr?.length ? "ARRAY[]::text[]" : `ARRAY[${arr.map(sqlString).join(",")}]`);
const sqlJsonb = (value) => (value === null || value === undefined ? "null" : `${sqlString(JSON.stringify(value))}::jsonb`);

function chunk(arr, size) {
  const out = [];
  for (let i = 0; i < arr.length; i += size) out.push(arr.slice(i, i + size));
  return out;
}

function kanjiInsert(entries) {
  const rows = entries
    .map(
      (k) =>
        `  (${sqlString(k.char)}, ${sqlString(k.meaning)}, ${sqlArray(k.onyomi)}, ${sqlArray(k.kunyomi)}, ${sqlInt(k.jlpt)})`
    )
    .join(",\n");
  return `insert into public.kanji (char, meaning, onyomi, kunyomi, jlpt) values\n${rows}\non conflict (char) do update set\n  meaning = excluded.meaning, onyomi = excluded.onyomi, kunyomi = excluded.kunyomi, jlpt = excluded.jlpt;`;
}

function wordInsert(entries) {
  const rows = entries
    .map((w) => {
      const components = extractKanjiComponents(w.word);
      return `  (${sqlString(w.word)}, ${sqlString(w.reading)}, ${sqlString(w.meaning)}, ${sqlArray(components)}, ${sqlInt(w.rank)}, ${sqlJsonb(w.senses)})`;
    })
    .join(",\n");
  return `insert into public.words (word, reading, meaning, components, rank, senses) values\n${rows}\non conflict (word) do update set\n  reading = excluded.reading, meaning = excluded.meaning, components = excluded.components, rank = excluded.rank, senses = excluded.senses;`;
}

const kanjiEntries = Object.values(KANJI);
const kanjiStatements = chunk(kanjiEntries, CHUNK_SIZE).map(kanjiInsert);
const wordStatements = chunk(WORDS, CHUNK_SIZE).map(wordInsert);

const sql = `-- Generated by scripts/generate-seed-sql.mjs from public/data/{kanji,words}.json.
-- Do not hand-edit -- regenerate instead so this can never drift from the
-- bundled offline dataset. Safe to re-run (upserts). Run once in the
-- Supabase SQL editor, after supabase/schema.sql.
--
-- ${kanjiEntries.length} kanji, ${WORDS.length} words, chunked into batches of
-- ${CHUNK_SIZE} rows per statement to keep each round-trip small.

${kanjiStatements.join("\n\n")}

${wordStatements.join("\n\n")}
`;

const outPath = path.join(ROOT, "supabase", "seed.sql");
writeFileSync(outPath, sql, "utf8");
console.log(`Wrote ${outPath} (${kanjiEntries.length} kanji, ${WORDS.length} words)`);
